const DICTS: Record<Lang, Dict> = { en, hi, mr };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

const KEY = "lexagent.lang";

export function setLang(lang: Lang) {
  writeKey(KEY, lang);
}

export function currentLang(): Lang {
  const v = readKey(KEY);
  return v === "hi" || v === "mr" ? v : "en";
}

/** The active language (English during server render) and its translator. */
export function useLang(): { lang: Lang; t: T } {
  const raw = useStoredKey(KEY);
  const lang: Lang = raw === "hi" || raw === "mr" ? raw : "en";
  return { lang, t: translator(lang) };
}
